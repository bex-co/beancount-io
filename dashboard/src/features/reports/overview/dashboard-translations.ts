/** Keys whose message is a count, written once per plural category. */
type PluralKey =
  | "atCostCount"
  | "monthsAverage"
  | "moreAccounts"
  | "notInTotalCount"
  | "pricesNotUpdated";
type PluralCategory = "one" | "two" | "few" | "many";

/**
 * Plural keys are flat `key_<category>` entries, as i18next resolves them from
 * `{ count }`, carrying exactly the categories each language uses
 * (`Intl.PluralRules`); `src/i18n/__tests__/plural.test.ts` fails on a missing
 * or extra one. Every other key keeps strict parity across languages.
 */
type DashboardMessages = {
  [K in Exclude<DashboardTranslationKey, PluralKey>]: string;
} & { [K in PluralKey as `${K}_other`]: string } & {
  [K in PluralKey as `${K}_${PluralCategory}`]?: string;
};

