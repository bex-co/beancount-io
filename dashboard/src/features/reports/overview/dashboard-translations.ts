function buildDashboardTranslations(
  language: DashboardLanguage,
): Record<string, DashboardTranslationEntry> {
  return Object.fromEntries(
    Object.entries(messages[language] as Record<string, string>).map(
      ([key, message]) => [
        `page.overview.${key}`,
        {
          message,
          description:
            descriptions[
              key.replace(PLURAL_SUFFIX, "") as DashboardTranslationKey
            ],
        },
      ],
    ),
  );
}

